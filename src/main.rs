//! # docker-fence
//!
//! Block Docker containers from opening *new* connections to a configured
//! list of networks, with optional exceptions.
//!
//! The configuration is a list of `block <cidr>` and `allow <cidr>` entries.
//! Where they overlap, the **most specific** entry (longest prefix) wins, so
//! a single device can be allowed inside a blocked network:
//!
//! ```text
//! block 192.0.2.0/24
//! allow 192.0.2.10/32
//! ```
//!
//! The tool manages a dedicated `DOCKER-FENCE` chain in the `filter` table
//! (for both iptables and ip6tables) and keeps a single jump to it at the top
//! of Docker's `DOCKER-USER` chain. Replies to connections that were
//! established from the outside (`ESTABLISHED,RELATED`) are always allowed;
//! any other traffic entering from `docker0` or a `br+` bridge is matched
//! against the entries, longest prefix first: `block` entries are rejected,
//! `allow` entries pass, and traffic matching no entry is unaffected.
//!
//! ## Usage
//!
//! ```text
//! docker-fence [--config PATH] <apply|remove|status>
//! ```
//!
//! | Subcommand | Effect                                                         |
//! |------------|----------------------------------------------------------------|
//! | `apply`    | Install the rules for the configured networks (idempotent)     |
//! | `remove`   | Remove the jump and the `DOCKER-FENCE` chain (ignores config)  |
//! | `status`   | Compare the installed rules against the configuration         |
//!
//! `--config` and `--dry` (alias `--dry-run`) are global options and may
//! appear before or after the subcommand. `--config` defaults to
//! [`config::DEFAULT_CONFIG_PATH`].
//!
//! ## Command echo and dry run
//!
//! Like `wg-quick`, every command that is executed is first printed to
//! stderr, prefixed with `[#]`. Rule scripts for `iptables-restore` are shown
//! as a heredoc:
//!
//! ```text
//! [#] iptables -w 10 -S DOCKER-USER
//! [#] iptables-restore -w 10 --noflush <<'EOF'
//! *filter
//! :DOCKER-FENCE - [0:0]
//! ...
//! COMMIT
//! EOF
//! ```
//!
//! With `--dry`, the `*-restore` commands are printed but not run, so
//! nothing is changed. Read-only `iptables -S` listings still run, since the
//! rules to install depend on the current state.
//!
//! ## Exit codes
//!
//! | Code | Meaning                                                              |
//! |------|----------------------------------------------------------------------|
//! | `0`  | Success (for `status`: every family is `ok` or `skipped`)            |
//! | `1`  | Runtime failure, or `status` found missing/mismatching rules         |
//! | `2`  | The configuration file could not be read or parsed                   |
//!
//! Command-line usage errors are reported by `clap` with its own exit code.
//!
//! ## Module overview
//!
//! * [`config`]   – parses the `block`/`allow` configuration file into a [`config::FenceConfig`].
//! * [`rules`]    – pure functions that render and parse iptables rule text.
//! * [`firewall`] – the [`firewall::Firewall`] abstraction over the iptables
//!   binaries, and its real implementation [`firewall::SystemFirewall`].
//! * [`ops`]      – the `apply`, `remove` and `status` operations, written
//!   against the [`firewall::Firewall`] trait so they can be tested with a fake.
//! * [`logging`]  – a minimal stderr logger for the `log` crate.

mod config;
mod firewall;
mod logging;
mod ops;
mod rules;

use std::path::{Path, PathBuf};
use std::process::ExitCode;

use clap::{Parser, Subcommand};
use config::DEFAULT_CONFIG_PATH;
use firewall::SystemFirewall;
use ops::{FamilyStatus, FenceError, Report};
use rules::Family;

/// Parsed command-line arguments.
#[derive(Debug, Parser)]
#[command(
    name = "docker-fence",
    version,
    about = "Block Docker containers from opening new connections to listed networks"
)]
struct Cli {
    /// Path to the configuration file
    #[arg(long, global = true, value_name = "PATH", default_value = DEFAULT_CONFIG_PATH)]
    config: PathBuf,
    /// Print the commands that would change the firewall without running them
    #[arg(long, global = true, alias = "dry-run")]
    dry: bool,
    /// The action to perform.
    #[command(subcommand)]
    command: Command,
}

/// The action selected on the command line.
///
/// The variant docs double as the `--help` text generated by `clap`.
#[derive(Debug, Subcommand)]
enum Command {
    /// Install the firewall rules for the configured networks
    Apply,
    /// Remove the firewall rules (ignores the configuration file)
    Remove,
    /// Check that the installed rules match the configuration
    Status,
}

/// Logs every notice in `report` at warning level and, for a dry run, a
/// closing reminder that nothing was changed.
fn print_notices(report: &Report, dry: bool) {
    for n in &report.notices {
        log::warn!("{n}");
    }
    if dry {
        log::info!("dry run: no changes were made");
    }
}

/// Logs `e` as an error and returns exit code `1`.
fn fail(e: &FenceError) -> ExitCode {
    log::error!("{e}");
    ExitCode::from(1)
}

/// Loads the configuration file at `path`.
///
/// # Errors
///
/// On failure the error is logged and the exit code to terminate with (`2`)
/// is returned in the `Err` variant, so callers can simply propagate it.
fn load_config(path: &Path) -> Result<config::FenceConfig, ExitCode> {
    config::load(path).map_err(|e| {
        log::error!("{e}");
        ExitCode::from(2)
    })
}

/// Returns the lowercase label (`"ipv4"` / `"ipv6"`) used in `status` output.
fn family_label(f: Family) -> &'static str {
    match f {
        Family::V4 => "ipv4",
        Family::V6 => "ipv6",
    }
}

/// Executes the subcommand selected in `cli` against the real firewall.
///
/// Every command is echoed to stderr as `[#] <command>`. With `--dry`, the
/// commands that would modify the firewall are echoed but not run; read-only
/// listings still run so the output reflects the real current state.
///
/// `remove` deliberately does not read the configuration file, so it keeps
/// working when the file is missing or broken. `status` prints one line per
/// address family to stdout (`ipv4: ok`, `ipv6: skipped (...)`, ...); all
/// diagnostics go to stderr through [`log`].
///
/// # Exit codes
///
/// * `0` – success; for `status`, all families are `ok` or `skipped`.
/// * `1` – an operation failed, or `status` found a missing/mismatching family.
/// * `2` – the configuration could not be loaded.
fn run(cli: &Cli) -> ExitCode {
    let fw = SystemFirewall { dry_run: cli.dry };
    match cli.command {
        Command::Apply => {
            let cfg = match load_config(&cli.config) {
                Ok(c) => c,
                Err(code) => return code,
            };
            match ops::apply(&fw, &cfg) {
                Ok(report) => {
                    print_notices(&report, cli.dry);
                    ExitCode::SUCCESS
                }
                Err(e) => fail(&e),
            }
        }
        Command::Remove => match ops::remove(&fw) {
            Ok(report) => {
                print_notices(&report, cli.dry);
                ExitCode::SUCCESS
            }
            Err(e) => fail(&e),
        },
        Command::Status => {
            let cfg = match load_config(&cli.config) {
                Ok(c) => c,
                Err(code) => return code,
            };
            match ops::status(&fw, &cfg) {
                Ok(report) => {
                    for (family, st) in &report.families {
                        let label = family_label(*family);
                        match st {
                            FamilyStatus::Ok => println!("{label}: ok"),
                            FamilyStatus::Skipped => {
                                println!("{label}: skipped (no DOCKER-USER chain)")
                            }
                            FamilyStatus::Missing => println!("{label}: missing"),
                            FamilyStatus::Mismatch(d) => println!("{label}: mismatch ({d})"),
                        }
                    }
                    if report.is_ok() {
                        ExitCode::SUCCESS
                    } else {
                        ExitCode::from(1)
                    }
                }
                Err(e) => fail(&e),
            }
        }
    }
}

/// Entry point: installs the stderr logger, parses arguments and dispatches
/// to [`run`].
fn main() -> ExitCode {
    logging::init();
    run(&Cli::parse())
}

#[cfg(test)]
mod tests {
    use super::*;
    use clap::error::ErrorKind;

    fn parse(v: &[&str]) -> Result<Cli, clap::Error> {
        Cli::try_parse_from(v)
    }

    #[test]
    fn default_config_path() {
        let cli = parse(&["docker-fence", "apply"]).unwrap();
        assert!(matches!(cli.command, Command::Apply));
        assert_eq!(cli.config, PathBuf::from(config::DEFAULT_CONFIG_PATH));
    }

    #[test]
    fn config_before_subcommand() {
        let cli = parse(&["docker-fence", "--config", "/tmp/x", "apply"]).unwrap();
        assert_eq!(cli.config, PathBuf::from("/tmp/x"));
    }

    #[test]
    fn config_after_subcommand() {
        let cli = parse(&["docker-fence", "status", "--config", "/tmp/y"]).unwrap();
        assert!(matches!(cli.command, Command::Status));
        assert_eq!(cli.config, PathBuf::from("/tmp/y"));
    }

    #[test]
    fn unknown_subcommand_is_error() {
        assert!(parse(&["docker-fence", "frobnicate"]).is_err());
    }

    #[test]
    fn missing_subcommand_is_error() {
        assert!(parse(&["docker-fence"]).is_err());
        assert!(parse(&["docker-fence", "--config", "/tmp/x"]).is_err());
    }

    #[test]
    fn config_without_value_is_error() {
        assert!(parse(&["docker-fence", "apply", "--config"]).is_err());
    }

    #[test]
    fn config_does_not_swallow_help_flag() {
        let err = parse(&["docker-fence", "--config", "--help", "apply"]).unwrap_err();
        assert_ne!(err.kind(), ErrorKind::DisplayHelp);
    }

    #[test]
    fn dry_flag_is_global_and_off_by_default() {
        assert!(!parse(&["docker-fence", "apply"]).unwrap().dry);
        assert!(parse(&["docker-fence", "--dry", "apply"]).unwrap().dry);
        assert!(parse(&["docker-fence", "remove", "--dry"]).unwrap().dry);
        assert!(parse(&["docker-fence", "status", "--dry-run"]).unwrap().dry);
    }

    #[test]
    fn two_subcommands_is_error() {
        assert!(parse(&["docker-fence", "apply", "status"]).is_err());
    }

    #[test]
    fn version_flag() {
        let err = parse(&["docker-fence", "--version"]).unwrap_err();
        assert_eq!(err.kind(), ErrorKind::DisplayVersion);
    }

    #[test]
    fn help_flag() {
        let err = parse(&["docker-fence", "--help"]).unwrap_err();
        assert_eq!(err.kind(), ErrorKind::DisplayHelp);
    }
}
